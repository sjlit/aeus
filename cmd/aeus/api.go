package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var pathParamRE = regexp.MustCompile(`:([A-Za-z_][A-Za-z0-9_]*)`)

const generatedTSHeader = "// Code generated by aeus gen. DO NOT EDIT."

type apiTypeInfo struct {
	source   string
	filePath string
	name     string
	fields   []manifestField
}

type apiIndex struct {
	messages map[string]apiTypeInfo
	enums    map[string]apiTypeInfo
}

// typeImports assigns one local alias per imported type. Proto types
// from different packages commonly share names (User, Item, ...), and
// an unaliased import would make the generated module ambiguous.
type typeImports struct {
	byPath map[string]map[string]string
	used   map[string]bool
}

func newTypeImports(m resourceManifest) *typeImports {
	used := map[string]bool{"http": true}
	for _, msg := range m.Messages {
		if msg.GoName != "" {
			used[msg.GoName] = true
		}
	}
	for _, e := range m.Enums {
		if e.GoName != "" {
			used[e.GoName] = true
		}
	}
	return &typeImports{byPath: map[string]map[string]string{}, used: used}
}

func (t *typeImports) add(path, name string) string {
	if path == "" || name == "" || name == "unknown" {
		return name
	}
	if existing := t.byPath[path][name]; existing != "" {
		return existing
	}
	alias := name
	for n := 2; t.used[alias]; n++ {
		alias = fmt.Sprintf("%s_%d", name, n)
	}
	t.used[alias] = true
	if t.byPath[path] == nil {
		t.byPath[path] = map[string]string{}
	}
	t.byPath[path][name] = alias
	return alias
}

func (t *typeImports) lines() []string {
	paths := make([]string, 0, len(t.byPath))
	for path := range t.byPath {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	var out []string
	for _, path := range paths {
		names := make([]string, 0, len(t.byPath[path]))
		for name := range t.byPath[path] {
			names = append(names, name)
		}
		sort.Strings(names)
		specs := make([]string, 0, len(names))
		for _, name := range names {
			alias := t.byPath[path][name]
			if alias == name {
				specs = append(specs, name)
			} else {
				specs = append(specs, name+" as "+alias)
			}
		}
		out = append(out, fmt.Sprintf("import type { %s } from '%s'", strings.Join(specs, ", "), path))
	}
	return out
}

func buildAPIIndex(manifests []resourceManifest, apiDir string) (*apiIndex, error) {
	idx := &apiIndex{
		messages: map[string]apiTypeInfo{},
		enums:    map[string]apiTypeInfo{},
	}
	for _, m := range manifests {
		path, err := apiFilePath(apiDir, m.Source)
		if err != nil {
			return nil, err
		}
		for _, msg := range m.Messages {
			idx.messages[apiTypeKey(m.GoPackage, msg.GoName)] = apiTypeInfo{
				source: m.Source, filePath: path, name: msg.GoName, fields: msg.Fields,
			}
		}
		for _, e := range m.Enums {
			idx.enums[apiTypeKey(m.GoPackage, e.GoName)] = apiTypeInfo{
				source: m.Source, filePath: path, name: e.GoName,
			}
		}
	}
	return idx, nil
}

func apiTypeKey(pkg, name string) string { return pkg + "." + name }

func (idx *apiIndex) resolve(ref *manifestRef, current resourceManifest, currentPath string) (string, string) {
	if ref == nil {
		return "", ""
	}
	switch ref.Kind {
	case "well_known":
		return wellKnownTS(ref.Name), ""
	case "message":
		return idx.resolveType(idx.messages, ref, current, currentPath)
	case "enum":
		return idx.resolveType(idx.enums, ref, current, currentPath)
	default:
		return "unknown", ""
	}
}

func (idx *apiIndex) resolveType(table map[string]apiTypeInfo, ref *manifestRef, current resourceManifest, currentPath string) (string, string) {
	if ref.Name == "" {
		return "unknown", ""
	}
	info, ok := table[apiTypeKey(ref.Package, ref.Name)]
	if !ok {
		return "unknown", ""
	}
	if info.filePath == currentPath {
		return info.name, ""
	}
	rel, err := filepath.Rel(filepath.Dir(currentPath), info.filePath)
	if err != nil {
		return "unknown", ""
	}
	rel = strings.TrimSuffix(filepath.ToSlash(rel), ".ts")
	if !strings.HasPrefix(rel, ".") {
		rel = "./" + rel
	}
	return info.name, rel
}

// generateAPIFiles writes TypeScript request/response types and wrappers
// for proto services that declare HTTP RPCs. Existing files without the
// generated header are treated as hand-written and left untouched;
// previously generated files are refreshed so proto changes propagate.
func generateAPIFiles(manifests []resourceManifest, apiDir string, check bool) (written, skipped int, missing []string, err error) {
	index, err := buildAPIIndex(manifests, apiDir)
	if err != nil {
		return 0, 0, nil, err
	}
	seen := map[string]bool{}
	for _, m := range manifests {
		path, err := apiFilePath(apiDir, m.Source)
		if err != nil {
			return 0, 0, nil, err
		}
		body := renderAPI(m, index, path)
		if body == "" {
			continue
		}
		if seen[path] {
			continue
		}
		seen[path] = true
		existing, readErr := os.ReadFile(path)
		if readErr == nil {
			// Files without the generated header are treated as
			// hand-written and are never touched. Generated files are
			// refreshed so proto changes propagate on the next run.
			if !strings.HasPrefix(string(existing), generatedTSHeader) {
				skipped++
				continue
			}
			if string(existing) == body {
				skipped++
				continue
			}
			if check {
				return 0, 0, nil, fmt.Errorf("%s is out of date; run `aeus gen`", path)
			}
			if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
				return 0, 0, nil, fmt.Errorf("write %s: %w", path, err)
			}
			written++
			continue
		} else if !os.IsNotExist(readErr) {
			return 0, 0, nil, fmt.Errorf("read %s: %w", path, readErr)
		}
		if check {
			missing = append(missing, path)
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return 0, 0, nil, fmt.Errorf("mkdir %s: %w", filepath.Dir(path), err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			return 0, 0, nil, fmt.Errorf("write %s: %w", path, err)
		}
		written++
	}
	return written, skipped, missing, nil
}

func apiFilePath(apiDir, source string) (string, error) {
	rel := strings.TrimSuffix(filepath.ToSlash(source), ".proto") + ".ts"
	clean := filepath.Clean(filepath.FromSlash(rel))
	if clean == "." || filepath.IsAbs(clean) ||
		clean == ".." || strings.HasPrefix(clean, ".."+string(filepath.Separator)) {
		return "", fmt.Errorf("invalid proto source %q", source)
	}
	return filepath.Join(apiDir, clean), nil
}

func renderAPI(m resourceManifest, index *apiIndex, currentPath string) string {
	hasMethod := false
	for _, svc := range m.Services {
		if len(svc.Methods) > 0 {
			hasMethod = true
			break
		}
	}
	if len(m.Messages) == 0 && len(m.Enums) == 0 && !hasMethod {
		return ""
	}

	imports := newTypeImports(m)
	var body strings.Builder

	enums := append([]manifestEnum(nil), m.Enums...)
	sort.Slice(enums, func(i, j int) bool { return enums[i].GoName < enums[j].GoName })
	for _, e := range enums {
		if e.GoName == "" {
			continue
		}
		numbers := make([]int32, 0, len(e.Values))
		seenNumbers := map[int32]bool{}
		for _, v := range e.Values {
			if !seenNumbers[v.Number] {
				seenNumbers[v.Number] = true
				numbers = append(numbers, v.Number)
			}
		}
		if len(numbers) == 0 {
			fmt.Fprintf(&body, "export type %s = number\n\n", e.GoName)
		} else {
			parts := make([]string, 0, len(numbers))
			for _, n := range numbers {
				parts = append(parts, fmt.Sprint(n))
			}
			fmt.Fprintf(&body, "export type %s = %s\n\n", e.GoName, strings.Join(parts, " | "))
		}
		fmt.Fprintf(&body, "export const %s = {\n", e.GoName)
		for _, v := range e.Values {
			fmt.Fprintf(&body, "  %s: %d,\n", v.Name, v.Number)
		}
		fmt.Fprintln(&body, "} as const")
		fmt.Fprintln(&body)
	}

	messages := append([]manifestMessage(nil), m.Messages...)
	sort.Slice(messages, func(i, j int) bool { return messages[i].GoName < messages[j].GoName })
	for _, msg := range messages {
		if msg.GoName == "" {
			continue
		}
		fmt.Fprintf(&body, "export interface %s {\n", msg.GoName)
		for _, f := range msg.Fields {
			if f.Name == "" {
				continue
			}
			typ := fieldTSType(f, m, index, currentPath, imports)
			fmt.Fprintf(&body, "  %s?: %s\n", f.Name, typ)
		}
		fmt.Fprintln(&body, "}")
		fmt.Fprintln(&body)
	}

	nameCounts := map[string]int{}
	for _, svc := range m.Services {
		for _, method := range svc.Methods {
			nameCounts[tsFunctionName(method.GoName)]++
		}
	}

	for _, svc := range m.Services {
		for _, method := range svc.Methods {
			name := tsFunctionName(method.GoName)
			if nameCounts[name] > 1 {
				name = lowerFirst(svc.GoName) + method.GoName
			}
			fmt.Fprintf(&body, "/** %s %s */\n", method.HTTPMethod, method.HTTPPath)
			reqType := method.Request
			if method.RequestRef != nil {
				if resolved, importPath := index.resolve(method.RequestRef, m, currentPath); resolved != "" {
					reqType = imports.add(importPath, resolved)
				}
			}
			if reqType == "" {
				reqType = "void"
			}
			respType := method.Response
			if method.ResponseRef != nil {
				if resolved, importPath := index.resolve(method.ResponseRef, m, currentPath); resolved != "" {
					respType = imports.add(importPath, resolved)
				}
			}
			if respType == "" {
				respType = "void"
			}
			params := ""
			if reqType != "void" {
				params = "req: " + reqType
			}
			fmt.Fprintf(&body, "export function %s(%s): Promise<%s> {\n", name, params, respType)

			pathExpr := renderPath(method.HTTPPath)
			fmt.Fprintf(&body, "  const path = `%s`\n", pathExpr)

			switch strings.ToUpper(method.HTTPMethod) {
			case "GET":
				fields := index.messageFields(m, method.RequestRef, reqType)
				pathParams := pathParamNames(method.HTTPPath)
				if query := renderQuery(fields, pathParams, m, index, currentPath, imports); query != "" {
					body.WriteString(query)
					fmt.Fprintln(&body, "  const query = params.toString()")
					fmt.Fprintf(&body, "  return http.get<%s>(`${path}${query ? `?${query}` : ''}`)\n", respType)
				} else {
					fmt.Fprintf(&body, "  return http.get<%s>(path)\n", respType)
				}
			default:
				call := strings.ToLower(method.HTTPMethod)
				args := ""
				if reqType != "void" {
					if method.Body == "*" {
						args = ", req"
					} else if method.Body != "" {
						args = ", req." + method.Body
					}
				}
				fmt.Fprintf(&body, "  return http.%s<%s>(path%s)\n", call, respType, args)
			}
			fmt.Fprintln(&body, "}")
			fmt.Fprintln(&body)
		}
	}

	var out strings.Builder
	fmt.Fprintln(&out, generatedTSHeader)
	fmt.Fprintln(&out)
	if hasMethod {
		fmt.Fprintln(&out, "import { http } from '@/api/http'")
	}
	if lines := imports.lines(); len(lines) > 0 {
		fmt.Fprintln(&out)
		for _, line := range lines {
			fmt.Fprintln(&out, line)
		}
	}
	fmt.Fprintln(&out)
	out.WriteString(body.String())
	return out.String()
}

func fieldTSType(f manifestField, m resourceManifest, index *apiIndex, currentPath string, imports *typeImports) string {
	base := fieldBaseType(f, m, index, currentPath, imports)
	if f.Map {
		return "Record<string, " + base + ">"
	}
	if f.List {
		return base + "[]"
	}
	return base
}

func fieldBaseType(f manifestField, m resourceManifest, index *apiIndex, currentPath string, imports *typeImports) string {
	base := f.Type
	if base == "" {
		base = "unknown"
	}
	if f.Ref == nil {
		return base
	}
	resolved, importPath := index.resolve(f.Ref, m, currentPath)
	if resolved == "" {
		resolved = "unknown"
	}
	return imports.add(importPath, resolved)
}

func wellKnownTS(name string) string {
	switch name {
	case "google.protobuf.Timestamp", "google.protobuf.Duration":
		return "{ seconds?: number; nanos?: number }"
	case "google.protobuf.FieldMask":
		return "{ paths?: string[] }"
	case "google.protobuf.StringValue", "google.protobuf.BytesValue":
		return "{ value?: string }"
	case "google.protobuf.BoolValue":
		return "{ value?: boolean }"
	case "google.protobuf.Int32Value", "google.protobuf.Int64Value",
		"google.protobuf.UInt32Value", "google.protobuf.UInt64Value",
		"google.protobuf.FloatValue", "google.protobuf.DoubleValue":
		return "{ value?: number }"
	default:
		return "unknown"
	}
}

func messageFields(m resourceManifest, name string) []manifestField {
	for _, msg := range m.Messages {
		if msg.GoName == name {
			return msg.Fields
		}
	}
	return nil
}

func (idx *apiIndex) messageFields(m resourceManifest, ref *manifestRef, name string) []manifestField {
	if ref != nil && ref.Kind == "message" {
		if info, ok := idx.messages[apiTypeKey(ref.Package, ref.Name)]; ok {
			return info.fields
		}
	}
	return messageFields(m, name)
}

func pathParamNames(path string) map[string]bool {
	out := map[string]bool{}
	for _, match := range pathParamRE.FindAllStringSubmatch(path, -1) {
		out[match[1]] = true
	}
	return out
}

func renderPath(path string) string {
	return pathParamRE.ReplaceAllStringFunc(path, func(token string) string {
		name := strings.TrimPrefix(token, ":")
		return "${encodeURIComponent(String(req." + name + "))}"
	})
}

func renderQuery(fields []manifestField, pathParams map[string]bool, m resourceManifest, index *apiIndex, currentPath string, imports *typeImports) string {
	var b strings.Builder
	any := false
	for _, f := range fields {
		if pathParams[f.Name] || f.Map {
			continue
		}
		base := fieldBaseType(f, m, index, currentPath, imports)
		isEnum := f.Ref != nil && f.Ref.Kind == "enum"
		if base != "string" && base != "number" && base != "boolean" && !isEnum {
			continue
		}
		if !any {
			fmt.Fprintln(&b, "  const params = new URLSearchParams()")
			any = true
		}
		if f.List {
			fmt.Fprintf(&b, "  if (Array.isArray(req.%s)) req.%s.forEach((v) => params.append(%q, String(v)))\n", f.Name, f.Name, f.Name)
			fmt.Fprintf(&b, "  else if (req.%s !== undefined && req.%s !== null) params.set(%q, String(req.%s))\n", f.Name, f.Name, f.Name, f.Name)
		} else {
			fmt.Fprintf(&b, "  if (req.%s !== undefined && req.%s !== null) params.set(%q, String(req.%s))\n", f.Name, f.Name, f.Name, f.Name)
		}
	}
	return b.String()
}

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

// tsReserved contains identifiers that cannot be used as a function
// declaration name in TypeScript. Proto method names are PascalCase,
// so common CRUD RPCs such as Delete would otherwise emit
// `export function delete(...)`, which is a syntax error.
var tsReserved = map[string]bool{
	"arguments": true, "eval": true,
	"await": true, "break": true, "case": true, "catch": true,
	"class": true, "const": true, "continue": true, "debugger": true,
	"default": true, "delete": true, "do": true, "else": true,
	"enum": true, "export": true, "extends": true, "false": true,
	"finally": true, "for": true, "function": true, "if": true,
	"implements": true, "import": true, "in": true, "instanceof": true,
	"interface": true, "let": true, "new": true, "null": true,
	"package": true, "private": true, "protected": true, "public": true,
	"return": true, "static": true, "super": true, "switch": true,
	"this": true, "throw": true, "true": true, "try": true,
	"typeof": true, "var": true, "void": true, "while": true,
	"with": true, "yield": true,
}

func tsFunctionName(goName string) string {
	name := lowerFirst(goName)
	if tsReserved[name] {
		return "rpc" + strings.ToUpper(name[:1]) + name[1:]
	}
	return name
}
