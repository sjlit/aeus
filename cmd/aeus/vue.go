package main

import (
	"fmt"
	"html"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

// generateVueFiles writes the SchemaViewer placeholder for every
// generated entity. Existing files are never overwritten: business
// pages are expected to grow hand-written behavior after the first
// generation.
func generateVueFiles(manifests []resourceManifest, webDir string, check bool) (written, skipped int, missing []string, err error) {
	seen := map[string]bool{}
	for _, m := range manifests {
		for _, e := range m.Entities {
			path, err := vueFilePath(webDir, e)
			if err != nil {
				return 0, 0, nil, err
			}
			if seen[path] {
				continue
			}
			seen[path] = true

			if _, statErr := os.Stat(path); statErr == nil {
				skipped++
				continue
			} else if !os.IsNotExist(statErr) {
				return 0, 0, nil, fmt.Errorf("stat %s: %w", path, statErr)
			}
			if check {
				missing = append(missing, path)
				continue
			}
			if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
				return 0, 0, nil, fmt.Errorf("mkdir %s: %w", filepath.Dir(path), err)
			}
			if err := os.WriteFile(path, []byte(renderVue(e)), 0o644); err != nil {
				return 0, 0, nil, fmt.Errorf("write %s: %w", path, err)
			}
			written++
		}
	}
	return written, skipped, missing, nil
}

func vueFilePath(webDir string, e manifestEntity) (string, error) {
	if e.Module == "" {
		return "", fmt.Errorf("%s: entity module is empty", e.GoName)
	}
	viewPath := strings.TrimSpace(e.ViewPath)
	if viewPath == "" {
		singular := e.Singular
		if singular == "" {
			singular = strings.TrimSuffix(e.Table, "s")
		}
		viewPath = "@/views/" + strings.ToLower(e.Module) + "/" + singular + "/Index.vue"
	}
	rel := strings.TrimPrefix(viewPath, "@/views/")
	rel = strings.TrimPrefix(rel, "@/")
	clean := filepath.Clean(filepath.FromSlash(rel))
	if clean == "." || filepath.IsAbs(clean) ||
		clean == ".." || strings.HasPrefix(clean, ".."+string(filepath.Separator)) {
		return "", fmt.Errorf("%s: invalid view_path %q", e.GoName, e.ViewPath)
	}
	return filepath.Join(webDir, clean), nil
}

func renderVue(e manifestEntity) string {
	component := pascalName(e.Module) + pascalName(e.Plural)
	if e.Plural == "" {
		component = pascalName(e.Module) + pascalName(e.Table)
	}
	title := e.MenuName
	if title == "" {
		title = e.Table
	}
	return fmt.Sprintf(`<!-- Code generated by aeus gen. DO NOT EDIT. -->
<script setup lang="ts">
// 与菜单 route meta.componentName 对齐，保证 keep-alive 能缓存页面。
defineOptions({ name: %s })

import { computed } from 'vue'
import { useRoute } from 'vue-router'
import { SchemaViewer } from '@sjlit/rest-ui'

const route = useRoute()

// 页面标题跟随菜单；未配置菜单时回落到表名。
const title = computed(() => (route.meta.title as string | undefined) || %s)
</script>

<template>
  <SchemaViewer module="%s" table="%s" :title="title" />
</template>
`, strconv.Quote(component), strconv.Quote(title), html.EscapeString(e.Module), html.EscapeString(e.Table))
}

func pascalName(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool {
		return r == '_' || r == '-' || r == ' ' || r == '/'
	})
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]))
		b.WriteString(p[1:])
	}
	return b.String()
}
